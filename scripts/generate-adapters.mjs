#!/usr/bin/env node
/**
 * Regenerate `src/engine/adapters.generated.ts` from the module directories.
 *
 * Mirrors `tools/module-manifest/generate.mjs` in the web project, and exists for the same
 * reason: Metro has no glob and Hermes rejects `import.meta`, so module discovery has to be a
 * checked-in file of static `import()` calls rather than something resolved at runtime.
 *
 * The loaders are deliberately lazy. `app/module/[id].tsx` used to import all 45 engines
 * statically — roughly 540 lines of imports feeding a 1,700-line adapter table — so opening any
 * one module bundled every module's engine, presentation and question bank. Metro code-splits a
 * static `import()`, so each module's wiring now arrives when a learner opens it.
 *
 *   node scripts/generate-adapters.mjs            # write the file
 *   node scripts/generate-adapters.mjs --check    # exit 1 if it has drifted (CI / npm run verify)
 */

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENGINE_DIR = join(ROOT, 'src/engine');
const OUT = join(ENGINE_DIR, 'adapters.generated.ts');

/** Every engine directory that carries an adapter, which is every module wired up for native. */
const moduleIds = readdirSync(ENGINE_DIR)
  .filter((name) => statSync(join(ENGINE_DIR, name)).isDirectory())
  .filter((name) => existsSync(join(ENGINE_DIR, name, 'adapter.ts')))
  .sort();

const body = `/**
 * Every module's native adapter, as lazy static imports.
 *
 * GENERATED by \`scripts/generate-adapters.mjs\` — do not edit. Run it after adding or removing a
 * module's \`adapter.ts\`; \`npm run verify\` checks it for you.
 *
 * Keyed by module id, which IS the engine directory name and the id in the file-synced
 * \`home/moduleRegistry.ts\`. The loaders are lazy on purpose: eagerly importing them welds every
 * module's engine, presentation and question bank into the first screen that touches this file.
 */

import type { AnyModuleAdapter } from './adapterTypes';

export type AdapterLoader = () => Promise<{ adapter: AnyModuleAdapter }>;

/** Module ids in directory order, which is alphabetical. */
export const ADAPTER_IDS: readonly string[] = [
${moduleIds.map((id) => `  '${id}',`).join('\n')}
];

export const adapterLoaders: Readonly<Record<string, AdapterLoader>> = {
${moduleIds.map((id) => `  ${id}: () => import('./${id}/adapter') as Promise<{ adapter: AnyModuleAdapter }>,`).join('\n')}
};
`;

const check = process.argv.includes('--check');
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;

if (check) {
  if (current !== body) {
    console.error('generate-adapters: src/engine/adapters.generated.ts is stale.');
    console.error('Run `npm run generate:adapters`.');
    process.exit(1);
  }
  console.log(`generate-adapters: ${moduleIds.length} adapter(s), manifest up to date.`);
} else {
  writeFileSync(OUT, body);
  console.log(`generate-adapters: wrote ${moduleIds.length} adapter(s).`);
}
